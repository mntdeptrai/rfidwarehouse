ALTER TABLE public.inbound_order_details DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.outbound_orders DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.outbound_order_details DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.sync_logs DISABLE ROW LEVEL SECURITY;
